u32 = ctypes.windll.user32
g32 = ctypes.windll.gdi32

def attach_to_default_desktop():
    try:
        hDesk = u32.OpenDesktopW("Default", 0, False, 0x01FF)
        if hDesk:
            u32.SetThreadDesktop(hDesk)
            return True
    except Exception:
        pass
    return False

attach_to_default_desktop()
pyautogui.FAILSAFE = False

class ScreenEdgeGlow:
    """Draws a 6px glowing border on all monitor edges via Windows GDI (Claude/Operator FX)"""
    def __init__(self, color_bgr=0x0088FF): # Cyber Orange / Claude Amber
        self.color = color_bgr
        self.is_running = False

    def start(self):
        self.is_running = True
        self.thread = threading.Thread(target=self._glow_loop, daemon=True)
        self.thread.start()

    def _glow_loop(self):
        attach_to_default_desktop()
        w = u32.GetSystemMetrics(0)
        h = u32.GetSystemMetrics(1)
        
        while self.is_running:
            hdc = u32.GetDC(0)
            if hdc:
                brush = g32.CreateSolidBrush(self.color)
                # Draw 6 nested rectangle outlines for a thick, glowing neon frame
                for i in range(6):
                    rect = (ctypes.c_long * 4)(i, i, w - i, h - i)
                    u32.FrameRect(hdc, rect, brush)
                g32.DeleteObject(brush)
                u32.ReleaseDC(0, hdc)
            time.sleep(0.04) # 25 FPS refresh to maintain visibility over repaints

    def stop(self):
        self.is_running = False
        time.sleep(0.05)
        attach_to_default_desktop()
        u32.InvalidateRect(0, None, True)

def smooth_move_mouse(end_x, end_y, duration=0.6):
    """Moves physical mouse cursor smoothly with easing curve."""
    attach_to_default_desktop()
    curr_x, curr_y = pyautogui.position()
    steps = int(duration * 60)
    for i in range(steps + 1):
        t = i / steps
        t_ease = t * t * (3 - 2 * t)
        nx = int(curr_x + (end_x - curr_x) * t_ease)
        ny = int(curr_y + (end_y - curr_y) * t_ease)
        u32.SetCursorPos(nx, ny)
        time.sleep(duration / steps)

def physical_mouse_click(x, y, delay_before=0.15):
    """Moves mouse directly to (x, y) and executes real left click."""
    attach_to_default_desktop()
    smooth_move_mouse(x, y, duration=0.55)
    time.sleep(delay_before)
    u32.mouse_event(0x0002, 0, 0, 0, 0) # LEFT DOWN
    time.sleep(0.06)
    u32.mouse_event(0x0004, 0, 0, 0, 0) # LEFT UP
    time.sleep(0.1)

def human_type_string(text):
    """Types text naturally with slight keystroke delays."""
    attach_to_default_desktop()
    for char in text:
        pyautogui.write(char)
        time.sleep(random.uniform(0.03, 0.07))

def physical_wheel_scroll(ticks=-6):
    """Rolls physical mouse wheel."""
    attach_to_default_desktop()
    for _ in range(abs(ticks)):
        direction = -1 if ticks < 0 else 1
        u32.mouse_event(0x0800, 0, 0, direction * 120, 0)
        time.sleep(0.09)

