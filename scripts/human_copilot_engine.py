import sys
import time
import math
import random
import ctypes
import pyautogui

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

try:
    import win32gui
    import win32con
except ImportError:
    win32gui = None

u32 = ctypes.windll.user32

def attach_to_default_desktop():
    """Forces thread attachment to the user's physical interactive screen."""
    try:
        hDesk = u32.OpenDesktopW("Default", 0, False, 0x01FF)
        if hDesk:
            u32.SetThreadDesktop(hDesk)
            return True
    except Exception:
        pass
    return False

attach_to_default_desktop()
pyautogui.FAILSAFE = False

def find_window_by_substr(substr):
    attach_to_default_desktop()
    if not win32gui: return None
    matches = []
    def enum_cb(hwnd, _):
        if win32gui.IsWindowVisible(hwnd):
            text = win32gui.GetWindowText(hwnd)
            if substr.lower() in text.lower():
                matches.append((hwnd, text))
    win32gui.EnumWindows(enum_cb, None)
    return matches[0] if matches else None

def bring_window_to_front(hwnd):
    attach_to_default_desktop()
    try:
        win32gui.ShowWindow(hwnd, win32con.SW_RESTORE)
        win32gui.SetForegroundWindow(hwnd)
        time.sleep(0.3)
        return True
    except Exception:
        try:
            win32gui.BringWindowToTop(hwnd)
            return True
        except:
            return False

def human_smooth_move(target_x, target_y, duration=0.6):
    """Moves cursor smoothly with human-like cubic acceleration and slight curve."""
    attach_to_default_desktop()
    curr_x, curr_y = pyautogui.position()
    steps = int(duration * 60)
    for i in range(steps + 1):
        t = i / steps
        t_ease = t * t * (3 - 2 * t)
        nx = int(curr_x + (target_x - curr_x) * t_ease)
        ny = int(curr_y + (target_y - curr_y) * t_ease)
        u32.SetCursorPos(nx, ny)
        time.sleep(duration / steps)

def human_type(text, min_delay=0.03, max_delay=0.08):
    """Types text key-by-key naturally as if a real person is sitting at the keyboard."""
    attach_to_default_desktop()
    for char in text:
        pyautogui.write(char)
        time.sleep(random.uniform(min_delay, max_delay))

def human_scroll(clicks=-4, delay=0.1):
    """Rolls the physical mouse wheel smoothly."""
    attach_to_default_desktop()
    # MOUSEEVENTF_WHEEL = 0x0800
    u32.mouse_event(0x0800, 0, 0, clicks * 120, 0)
    time.sleep(delay)

def browse_website_visually(url):
    """
    Physically focuses the browser, opens a new tab, types the URL letter-by-letter,
    presses Enter, and scrolls the webpage right before the user's eyes!
    """
    attach_to_default_desktop()
    print(f"🌐 [Human Co-Pilot] Visually navigating to: {url}")

    # 1. البحث عن المتصفح النشط (Brave أو Chrome أو Edge)
    browser_match = find_window_by_substr("Brave") or find_window_by_substr("Chrome") or find_window_by_substr("Edge")
    if browser_match:
        hwnd, title = browser_match
        print(f"🎯 [Human Co-Pilot] Bringing browser to front: {title[:40]}...")
        bring_window_to_front(hwnd)
        time.sleep(0.5)
    else:
        print("🚀 [Human Co-Pilot] Browser not open, launching Brave/Chrome...")
        pyautogui.press("win")
        time.sleep(0.4)
        human_type("Brave", min_delay=0.05, max_delay=0.1)
        pyautogui.press("enter")
        time.sleep(2.5)

    # 2. فتح تبويب جديد عبر اختصار الكيبورد
    print("⌨️ [Human Co-Pilot] Opening new tab (Ctrl+T)...")
    pyautogui.hotkey("ctrl", "t")
    time.sleep(0.6)

    # 3. كتابة الرابط حرفاً بحرف بسرعة بشرية طبيعية
    print(f"✍️ [Human Co-Pilot] Typing URL letter-by-letter: {url}")
    human_type(url, min_delay=0.025, max_delay=0.06)
    time.sleep(0.3)

    # 4. الضغط على Enter للدخول
    print("⏎ [Human Co-Pilot] Pressing Enter to navigate...")
    pyautogui.press("enter")
    time.sleep(3.0)

    # 5. تحريك الماوس إلى منتصف الصفحة والتمرير لأسفل ولأعلى
    w = u32.GetSystemMetrics(0)
    h = u32.GetSystemMetrics(1)
    cx, cy = w // 2, h // 2

    print("🖱️ [Human Co-Pilot] Moving mouse to center of page and scrolling...")
    human_smooth_move(cx, cy, duration=0.6)
    time.sleep(0.4)

    # التمرير لأسفل لمشاهدة محتوى الصفحة
    for _ in range(6):
        human_scroll(clicks=-3, delay=0.18)

    time.sleep(1.2)

    # التمرير لأعلى مجدداً
    for _ in range(6):
        human_scroll(clicks=3, delay=0.18)

    print("✨ [Human Co-Pilot] Visual browsing action completed right in front of you!")

