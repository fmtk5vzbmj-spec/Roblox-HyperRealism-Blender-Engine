u32 = ctypes.windll.user32

def attach_to_default_desktop():
    try:
        hDesk = u32.OpenDesktopW("Default", 0, False, 0x01FF)
        if hDesk:
            u32.SetThreadDesktop(hDesk)
            return True
    except Exception:
        pass
    return False

attach_to_default_desktop()
pyautogui.FAILSAFE = False

class ScreenGlowOverlay:
    """Full-screen glowing frame overlay (like Claude 3.5 Computer Use / ChatGPT Operator)"""
    def __init__(self, color="#ff6600"): # Claude Amber / Cyber Orange by default
        self.color = color
        self.root = None
        self.canvas = None
        self.is_active = False

    def start(self, duration_sec=None):
        attach_to_default_desktop()
        self.is_active = True
        self.thread = threading.Thread(target=self._run_window, args=(duration_sec,), daemon=True)
        self.thread.start()
        time.sleep(0.4) # Wait for window to render

    def _run_window(self, duration_sec):
        attach_to_default_desktop()
        self.root = tk.Tk()
        self.root.title("AI Operator Glow")
        self.root.overrideredirect(True)
        self.root.attributes("-topmost", True)
        self.root.attributes("-transparentcolor", "black")

        w = u32.GetSystemMetrics(0)
        h = u32.GetSystemMetrics(1)
        self.root.geometry(f"{w}x{h}+0+0")

        # Make window click-through (WS_EX_TRANSPARENT | WS_EX_LAYERED)
        self.root.update_idletasks()
        hwnd = self.root.winfo_id()
        GWL_EXSTYLE = -20
        style = u32.GetWindowLongW(hwnd, GWL_EXSTYLE)
        u32.SetWindowLongW(hwnd, GWL_EXSTYLE, style | 0x80000 | 0x20)

        self.canvas = tk.Canvas(self.root, width=w, height=h, bg="black", highlightthickness=0)
        self.canvas.pack(fill=tk.BOTH, expand=True)

        # Draw glowing neon borders on all 4 edges (Claude / Operator Style)
        border_thickness = 5
        # Outer glow
        self.canvas.create_rectangle(1, 1, w - 1, h - 1, outline=self.color, width=border_thickness)
        self.canvas.create_rectangle(4, 4, w - 4, h - 4, outline="#ffaa00", width=2)

        # Top Center Operator Pill Badge
        badge_w, badge_h = 380, 36
        bx1, by1 = (w - badge_w) // 2, 8
        bx2, by2 = bx1 + badge_w, by1 + badge_h
        
        self.canvas.create_rectangle(bx1, by1, bx2, by2, fill="#120800", outline=self.color, width=2)
        self.canvas.create_text(
            w // 2, by1 + 18,
            text="⚡ AI OPERATOR ACTIVE | CONTROLLING SCREEN",
            fill="#ffcc00",
            font=("Segoe UI", 10, "bold")
        )

        if duration_sec:
            self.root.after(int(duration_sec * 1000), self.stop)

        try:
            self.root.mainloop()
        except:
            pass

    def stop(self):
        self.is_active = False
        if self.root:
            try:
                self.root.after(0, self.root.destroy)
            except:
                pass

def trigger_click_ripple(x, y):
    """Spawns an expanding animated ripple halo where the AI clicks."""
    attach_to_default_desktop()
    def _ripple():
        try:
            r = tk.Tk()
            r.overrideredirect(True)
            r.attributes("-topmost", True)
            r.attributes("-transparentcolor", "black")
            size = 64
            r.geometry(f"{size}x{size}+{int(x - size/2)}+{int(y - size/2)}")
            c = tk.Canvas(r, width=size, height=size, bg="black", highlightthickness=0)
            c.pack()
            c.create_oval(3, 3, size-3, size-3, outline="#ff6600", width=3)
            c.create_oval(14, 14, size-14, size-14, outline="#00ffcc", width=2)
            c.create_oval(26, 26, size-26, size-26, fill="#ffffff", outline="")
            r.after(320, r.destroy)
            r.mainloop()
        except:
            pass
    threading.Thread(target=_ripple, daemon=True).start()

def physical_smooth_move(end_x, end_y, duration=0.6):
    """Physically glides the hardware mouse cursor smoothly across the screen."""
    attach_to_default_desktop()
    curr_x, curr_y = pyautogui.position()
    steps = int(duration * 60)
    for i in range(steps + 1):
        t = i / steps
        t_ease = t * t * (3 - 2 * t)
        nx = int(curr_x + (end_x - curr_x) * t_ease)
        ny = int(curr_y + (end_y - curr_y) * t_ease)
        u32.SetCursorPos(nx, ny)
        time.sleep(duration / steps)

def physical_click(x, y, delay=0.15):
    """Moves mouse directly to element, clicks physically, and triggers ripple."""
    attach_to_default_desktop()
    physical_smooth_move(x, y, duration=0.5)
    time.sleep(delay)
    trigger_click_ripple(x, y)
    u32.mouse_event(0x0002, 0, 0, 0, 0) # LEFT DOWN
    time.sleep(0.06)
    u32.mouse_event(0x0004, 0, 0, 0, 0) # LEFT UP
    time.sleep(0.1)

def human_type_keys(text):
    """Types text naturally key-by-key."""
    attach_to_default_desktop()
    for char in text:
        pyautogui.write(char)
        time.sleep(random.uniform(0.03, 0.07))

def physical_scroll_wheel(amount=-5):
    """Rolls the physical mouse wheel."""
    attach_to_default_desktop()
    for _ in range(abs(amount)):
        direction = -1 if amount < 0 else 1
        u32.mouse_event(0x0800, 0, 0, direction * 120, 0)
        time.sleep(0.08)

