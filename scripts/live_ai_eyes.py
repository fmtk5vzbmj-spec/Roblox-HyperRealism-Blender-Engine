import time
import threading
import sys
import os
import mss
import numpy as np
import pyautogui

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

try:
    import win32gui
except ImportError:
    win32gui = None

try:
    import tkinter as tk
except ImportError:
    tk = None

class LiveAIEyes:
    def __init__(self, target_fps=30, enable_hud=True):
        self.target_fps = target_fps
        self.frame_delay = 1.0 / target_fps
        self.is_running = False
        self.mode = "OBSERVING" # "OBSERVING" or "CONTROLLING"
        self.sct = mss.mss()
        self.monitor = self.sct.monitors[1]
        self.last_frame = None
        self.enable_hud = enable_hud
        self.hud_root = None
        self.hud_frame = None
        self.hud_label = None
        self.hud_badge = None

        self.current_state = {
            "fps": 0,
            "mode": "OBSERVING",
            "motion_detected": False,
            "motion_percentage": 0.0,
            "active_app": "Unknown",
            "mouse_pos": (0, 0),
            "roblox_active": False,
            "timestamp": time.time()
        }

    def set_mode(self, mode_name):
        """Switches between 'OBSERVING' (Cyan) and 'CONTROLLING' (Crimson)"""
        self.mode = mode_name.upper()
        self.current_state["mode"] = self.mode
        if self.hud_root:
            self.hud_root.after(0, self._update_hud_colors)

    def trigger_click_ripple(self, x, y):
        """Spawns a vibrant circular halo/ripple effect right on the screen at (x, y)"""
        if not tk:
            return
        def _spawn_ripple():
            try:
                ripple = tk.Toplevel()
                ripple.overrideredirect(True)
                ripple.attributes("-topmost", True)
                ripple.attributes("-transparentcolor", "black")
                
                size = 54
                ripple.geometry(f"{size}x{size}+{int(x - size/2)}+{int(y - size/2)}")
                canvas = tk.Canvas(ripple, width=size, height=size, bg="black", highlightthickness=0)
                canvas.pack()

                # Draw glowing cyber rings
                canvas.create_oval(4, 4, size-4, size-4, outline="#ff0055", width=3)
                canvas.create_oval(14, 14, size-14, size-14, outline="#00ffcc", width=2)
                canvas.create_oval(23, 23, size-23, size-23, fill="#ffffff", outline="")

                ripple.after(280, ripple.destroy)
            except Exception:
                pass

        if self.hud_root:
            self.hud_root.after(0, _spawn_ripple)
        else:
            threading.Thread(target=_spawn_ripple, daemon=True).start()

    def start_vision_stream(self):
        """Starts in-memory frame capture and HUD."""
        self.is_running = True
        self.stream_thread = threading.Thread(target=self._vision_loop, daemon=True)
        self.stream_thread.start()
        print("[Live AI Eyes] Vision stream active (Zero-disk RAM pipeline)!")

        if self.enable_hud and tk:
            self._start_floating_eye_hud()
        else:
            try:
                while self.is_running:
                    time.sleep(1.0)
            except KeyboardInterrupt:
                self.stop()

    def _vision_loop(self):
        frame_count = 0
        fps_timer = time.time()

        while self.is_running:
            loop_start = time.time()

            raw_img = self.sct.grab(self.monitor)
            frame = np.array(raw_img, dtype=np.uint8)

            motion_percent = 0.0
            if self.last_frame is not None:
                diff = np.abs(frame[::8, ::8, :3].astype(int) - self.last_frame[::8, ::8, :3].astype(int))
                motion_pixels = np.sum(diff > 25)
                motion_percent = (motion_pixels / diff.size) * 100.0

            self.last_frame = frame
            current_mouse = pyautogui.position()
            current_window = self._get_active_window_title()
            is_roblox = "roblox" in current_window.lower()

            frame_count += 1
            if time.time() - fps_timer >= 1.0:
                self.current_state["fps"] = frame_count
                frame_count = 0
                fps_timer = time.time()

            self.current_state["motion_detected"] = motion_percent > 0.4
            self.current_state["motion_percentage"] = round(motion_percent, 2)
            self.current_state["active_app"] = current_window
            self.current_state["mouse_pos"] = (current_mouse.x, current_mouse.y)
            self.current_state["roblox_active"] = is_roblox
            self.current_state["timestamp"] = time.time()

            if self.hud_label and self.hud_root:
                self.hud_root.after(0, self._refresh_hud_text)

            elapsed = time.time() - loop_start
            sleep_time = max(0, self.frame_delay - elapsed)
            time.sleep(sleep_time)

    def _get_active_window_title(self):
        if not win32gui:
            return "Active App"
        try:
            hwnd = win32gui.GetForegroundWindow()
            return win32gui.GetWindowText(hwnd) or "Desktop"
        except:
            return "Unknown"

    def _update_hud_colors(self):
        if not self.hud_frame or not self.hud_badge:
            return
        if self.mode == "CONTROLLING":
            # Active AI takeover - Crimson Red / Electric Amber
            self.hud_frame.configure(highlightbackground="#ff0055", highlightcolor="#ff0055")
            self.hud_badge.configure(text="⚡ AI HANDS: ACTIVE CONTROL", fg="#ff0055")
            self.hud_label.configure(fg="#ffccdd")
        else:
            # Passive AI watching - Emerald / Cyan Neon
            self.hud_frame.configure(highlightbackground="#00ffcc", highlightcolor="#00ffcc")
            self.hud_badge.configure(text="👁️ AI EYES: LIVE & WATCHING", fg="#00ffcc")
            self.hud_label.configure(fg="#b3fff0")

    def _refresh_hud_text(self):
        if not self.hud_label:
            return
        s = self.current_state
        self.hud_label.config(
            text=f"App: {s['active_app'][:26]}\nFPS: {s['fps']} | Cursor: {s['mouse_pos']}\n[by elyr (b84_) - 80% AI]"
        )

    def _start_floating_eye_hud(self):
        self.hud_root = tk.Tk()
        self.hud_root.title("AI Live Vision")
        self.hud_root.overrideredirect(True)
        self.hud_root.attributes("-topmost", True)
        self.hud_root.attributes("-alpha", 0.88)

        sw = self.hud_root.winfo_screenwidth()
        self.hud_root.geometry(f"250x85+{sw - 265}+20")
        self.hud_root.configure(bg="#080c14")

        self.hud_frame = tk.Frame(self.hud_root, bg="#080c14", highlightbackground="#00ffcc", highlightthickness=2)
        self.hud_frame.pack(fill=tk.BOTH, expand=True)

        self.hud_badge = tk.Label(
            self.hud_frame,
            text="👁️ AI EYES: LIVE & WATCHING",
            font=("Segoe UI", 9, "bold"),
            fg="#00ffcc",
            bg="#080c14",
            padx=8,
            pady=2
        )
        self.hud_badge.pack(anchor="w")

        self.hud_label = tk.Label(
            self.hud_frame,
            text="Initializing Live Stream...",
            font=("Consolas", 8),
            fg="#b3fff0",
            bg="#080c14",
            justify=tk.LEFT,
            padx=8,
            pady=2
        )
        self.hud_label.pack(fill=tk.BOTH, expand=True)

        self.hud_root.bind("<Double-Button-1>", lambda e: self.stop())

        try:
            self.hud_root.mainloop()
        except:
            pass

    def stop(self):
        self.is_running = False
        if self.hud_root:
            try:
                self.hud_root.destroy()
            except:
                pass
        print("[Live AI Eyes] Vision stream stopped.")

    def get_live_perception(self):
        return self.current_state

if __name__ == "__main__":
    enable_hud = "--no-hud" not in sys.argv
    eyes = LiveAIEyes(target_fps=30, enable_hud=enable_hud)
    eyes.start_vision_stream()
